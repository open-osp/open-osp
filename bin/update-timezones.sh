#!/bin/bash
# update-timezones.sh — apply IANA tzdata updates (e.g. BC permanent UTC-7,
# tzdata 2026b/2026c) across the Open OSP stack with minimal risk.
#
# Verified end-to-end 2026-09-08. See doc/timezone-update-runbook.md.
#
# Modes:
#   --check     read-only probes of all layers; exits non-zero on failure
#   --merge-only  build docker-compose.override.yml from template + dc.dev.yml; no rollout
#   --apply     backup -> build overlays -> merge compose -> rollout -> verify
#   --rollback  remove overlays (re-pull upstream images), keep port mappings
#
# The merge preserves everything in docker-compose.override.yml except the
# image:/build: blocks of the four stack services; port mappings are kept
# from the existing file or dc.dev.yml.

set -euo pipefail
cd "$(dirname "$0")/.."

MODE="${1:---check}"
TZ_TEMPLATE="docker-compose.tz.yml"
OVERRIDE="docker-compose.override.yml"
DCDEV="dc.dev.yml"
BACKUP_DIR="${BACKUP_DIR:-$HOME/openosp-backups}"
PROBE_DATE="${PROBE_DATE:-2026-12-15}"       # a date after the BC change
PROBE_UTC_HOUR="${PROBE_UTC_HOUR:-19}"       # expected CONVERT_TZ result (UTC-7)

green()  { printf '\033[32m%s\033[0m\n' "$*"; }
red()    { printf '\033[31m%s\033[0m\n' "$*"; }
yellow() { printf '\033[33m%s\033[0m\n' "$*"; }

[ -f local.env ] || { red "local.env missing — run ./openosp setup first"; exit 1; }
PW=$(grep '^MYSQL_ROOT_PASSWORD=' local.env | cut -d= -f2-)
[ -n "$PW" ] || { red "MYSQL_ROOT_PASSWORD not set"; exit 1; }

dc() { docker compose "$@"; }
dbq() { dc exec -e PW="$PW" db sh -c "mysql -uroot -p\"\$PW\" $1"; }

# ---------------------------------------------------------------------------
# Verification probes
# ---------------------------------------------------------------------------
FAIL=0
note() { if [ "$1" = 0 ]; then green "  PASS: $2"; else red "  FAIL: $2"; FAIL=1; fi; }

check_os() {  # $1=container  $2=label
  out=$(dc exec "$1" sh -c "TZ=America/Vancouver date -d \"$PROBE_DATE 12:00\" +%z" 2>/dev/null | tr -d '\r')
  [ "$out" = "-0700" ]; note $? "$2 OS zoneinfo: $PROBE_DATE -> ${out:-<down>}"
}

check_sql() {
  out=$(dbq "-N -e \"SELECT CONVERT_TZ('$PROBE_DATE 12:00:00','America/Vancouver','UTC')\"" 2>/dev/null | grep -oE '[0-9]{2}:[0-9]{2}:[0-9]{2}' | head -1)
  [ "$out" = "$PROBE_UTC_HOUR:00:00" ]; note $? "SQL CONVERT_TZ: $PROBE_DATE -> ${out:-<none>}"
}

check_jvm_file() {  # tzdb.dat on disk + running JVM booted after image bake
  for c in oscar expedius faxws; do
    ver=$(dc exec "$c" sh -c 'grep -a -m1 -o "20[0-9][0-9][a-z]" /opt/java/openjdk/lib/tzdb.dat' 2>/dev/null | tr -d '\r')
    case "$ver" in
      2026b|2026c|2027*) green "  PASS: $c JVM tzdb.dat = $ver";;
      "") red "  FAIL: $c tzdb.dat unreadable"; FAIL=1;;
      *)  red "  FAIL: $c JVM tzdb.dat = $ver (needs >= 2026b)"; FAIL=1;;
    esac
    boot=$(dc exec "$c" sh -c 'ps -o lstart= -p $(pidof java)' 2>/dev/null | tr -d '\r')
    bake=$(dc exec "$c" sh -c 'stat -c %Y /opt/java/openjdk/lib/tzdb.dat' 2>/dev/null | tr -d '\r')
    bootn=$(date -d "$boot" +%s 2>/dev/null || echo 0)
    [ -n "$bake" ] && [ "$bootn" -gt "$bake" ]; note $? "$c running JVM booted ($boot) after tzdb.dat bake"
  done
}

check_app() {
  code=$(curl -s -o /dev/null -w '%{http_code}' -m 10 "http://localhost:8080/oscar/" || true)
  { [ "$code" = "302" ] || [ "$code" = "200" ]; }; note $? "OSCAR app responds (HTTP $code)"
}

check_all() {
  yellow "== Timezone verification =="
  check_jvm_file
  for c in oscar expedius faxws db; do check_os "$c" "$c"; done
  check_sql
  out=$(dbq "-N -e \"SELECT TIMEDIFF(NOW(), UTC_TIMESTAMP())\"" 2>/dev/null | tr -d '\r')
  [ "$out" = "-07:00:00" ]; note $? "MariaDB live clock offset: ${out:-<none>}"
  check_app
  if [ "$FAIL" = 0 ]; then green "== ALL CHECKS PASSED =="; else red "== FAILURES PRESENT =="; fi
  return "$FAIL"
}

# ---------------------------------------------------------------------------
# Compose override merge (python3 + pyyaml; preserves unrelated config)
# ---------------------------------------------------------------------------
merge_override() {
  python3 - "$OVERRIDE" "$DCDEV" "$TZ_TEMPLATE" <<'PYEOF'
import sys, yaml
override_p, dcdev_p, template_p = sys.argv[1:4]
import os
base = {}
if os.path.exists(override_p):
    base = yaml.safe_load(open(override_p)) or {}
dcdev = yaml.safe_load(open(dcdev_p)) or {} if os.path.exists(dcdev_p) else {}
tmpl  = yaml.safe_load(open(template_p)) or {}

services = base.setdefault('services', {})
for name, tsvc in (tmpl.get('services') or {}).items():
    svc = dict(services.get(name) or {})
    # keep explicit ports: existing > dc.dev > template
    ports = (services.get(name) or {}).get('ports') or (dcdev.get('services', {}) or {}).get(name, {}).get('ports') or tsvc.get('ports')
    svc.update(tsvc)
    if ports: svc['ports'] = ports
    services[name] = svc

header = ("# Generated by bin/update-timezones.sh — local override.\n"
          "# Combines your previous local settings with tzdata overlay image/build blocks\n"
          "# (template: docker-compose.tz.yml). Ports preserved. Regenerate via the script.\n")
with open(override_p, 'w') as f:
    f.write(header)
    yaml.safe_dump(base, f, sort_keys=False, default_flow_style=False)
print(f"merged -> {override_p}")
PYEOF
}

strip_override() {
  python3 - "$OVERRIDE" "$DCDEV" <<'PYEOF'
import sys, yaml, os
override_p, dcdev_p = sys.argv[1:3]
base = yaml.safe_load(open(override_p)) or {} if os.path.exists(override_p) else {}
dcdev = yaml.safe_load(open(dcdev_p)) or {} if os.path.exists(dcdev_p) else {}
services = base.setdefault('services', {})
for name, dsvc in (dcdev.get('services') or {}).items():
    svc = dict(services.get(name) or {})
    for k in ('image', 'build'):
        svc.pop(k, None)
    if dsvc.get('ports'): svc['ports'] = dsvc['ports']
    if svc: services[name] = svc
    else: services.pop(name, None)
if not services: base.pop('services', None)
if not base:
    os.remove(override_p); print("override empty -> removed")
else:
    with open(override_p, 'w') as f:
        f.write("# Generated by bin/update-timezones.sh --rollback (tz overlays removed, ports kept).\n")
        yaml.safe_dump(base, f, sort_keys=False, default_flow_style=False)
    print(f"stripped -> {override_p}")
PYEOF
}

db_backup() {
  mkdir -p "$BACKUP_DIR"
  local f="$BACKUP_DIR/pre-tzupdate-$(date +%Y%m%d-%H%M%S).sql"
  dc exec -e PW="$PW" db sh -c 'mysqldump -uroot -p"$PW" --databases oscar drugref2 --single-transaction' > "$f" 2>/dev/null
  [ -s "$f" ] && green "backup: $f ($(du -h "$f" | cut -f1))" || { red "backup failed"; exit 1; }
}

load_tz_tables() {
  dc exec -e PW="$PW" db sh -c 'mysql_tzinfo_to_sql /usr/share/zoneinfo 2>/dev/null | mysql -uroot -p"$PW" mysql' \
    && green "SQL time zone tables regenerated" || { red "mysql_tzinfo_to_sql failed"; exit 1; }
}

# ---------------------------------------------------------------------------
case "$MODE" in
  --check)
    check_all
    ;;
  --merge-only)
    merge_override
    ;;
  --apply)
    yellow "== 1/6 backup ==";        db_backup
    yellow "== 2/6 merge compose =="; merge_override
    yellow "== 3/6 build overlays =="; dc build oscar expedius faxws db | tail -4
    yellow "== 4/6 rollout db ==";    dc up -d db; sleep 12; load_tz_tables
    yellow "== 5/6 rollout apps ==";  dc up -d oscar expedius faxws
    yellow "== 6/6 wait for OSCAR =="
    for i in $(seq 1 30); do
      code=$(curl -s -o /dev/null -w '%{http_code}' -m 5 http://localhost:8080/oscar/ || true)
      { [ "$code" = "302" ] || [ "$code" = "200" ]; } && { green "OSCAR up (after ~$((i*10))s)"; break; }
      sleep 10
    done
    check_all
    ;;
  --rollback)
    yellow "== rollback: removing tz overlays =="
    strip_override
    docker compose pull oscar expedius faxws db | tail -4
    dc up -d db; sleep 12; load_tz_tables
    dc up -d oscar expedius faxws
    yellow "rolled back to upstream images; re-checking:"
    check_all || true
    ;;
  *)
    red "usage: $0 [--check|--merge-only|--apply|--rollback]"; exit 1
    ;;
esac
